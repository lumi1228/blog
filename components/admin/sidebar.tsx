interface AdminSidebarProps {
  userEmail: string;
}

export function AdminSidebar({ userEmail }: AdminSidebarProps) {
  const pathname = usePathname();
  const router = useRouter();

  const handleLogout = async () => {
    const supabase = createClient();
    await supabase.auth.signOut();
    router.push("/admin/login");
    router.refresh();
  };

  return (
    <aside className="flex w-56 flex-col border-r border-[var(--border-subtle)] bg-[var(--bg-secondary)]">
      {/* Logo */}
      <div className="flex h-16 items-center border-b border-[var(--border-subtle)] px-5">
        <Link
          href="/admin/dashboard"
          className="text-lg font-semibold text-[var(--text-primary)]"
          style={{ fontFamily: "var(--font-display)" }}
        >
          <span className="text-[var(--accent-primary)]">L</span>umi
          <span className="ml-2 text-xs font-normal text-[var(--text-tertiary)]">Admin</span>
        </Link>
      </div>

      {/* 导航 */}
      <nav className="flex-1 space-y-1 px-3 py-4">
        {navItems.map((item) => {
          const isActive = pathname === item.href || pathname.startsWith(item.href + "/");
          return (
            <Link
              key={item.href}
              href={item.href}
              className={`flex items-center gap-2.5 rounded-[var(--radius-md)] px-3 py-2 text-sm font-medium
                         transition-colors duration-[var(--duration-fast)]
                         ${
                           isActive
                             ? "bg-[var(--accent-muted)] text-[var(--accent-primary)]"
                             : "text-[var(--text-secondary)] hover:bg-[var(--bg-tertiary)] hover:text-[var(--text-primary)]"
                         }`}
            >
              {item.icon}
              {item.label}
            </Link>
          );
        })}
      </nav>

      {/* 底部用户信息 */}
      <div className="border-t border-[var(--border-subtle)] p-3">
        <div className="mb-2 truncate px-3 text-xs text-[var(--text-tertiary)]">
          {userEmail}
        </div>
        <button
          onClick={handleLogout}
          className="flex w-full items-center gap-2 rounded-[var(--radius-md)] px-3 py-2 text-sm 
                     text-[var(--text-secondary)] transition-colors duration-[var(--duration-fast)]
                     hover:bg-[var(--bg-tertiary)] hover:text-[var(--error)]"
        >
          <svg className="h-4 w-4" fill="none" viewBox="0 0 24 24" stroke="currentColor" strokeWidth={1.5}>
            <path strokeLinecap="round" strokeLinejoin="round" d="M15.75 9V5.25A2.25 2.25 0 0013.5 3h-6a2.25 2.25 0 00-2.25 2.25v13.5A2.25 2.25 0 007.5 21h6a2.25 2.25 0 002.25-2.25V15m3 0l3-3m0 0l-3-3m3 3H9" />
          </svg>
          退出登录
        </button>
      </div>
    </aside>
  );
}
